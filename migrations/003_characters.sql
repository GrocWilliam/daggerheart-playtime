CREATE TABLE IF NOT EXISTS characters (
	id text PRIMARY KEY DEFAULT gen_random_uuid()::text,
	campaign_id text NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
	name text NOT NULL,
	class text NOT NULL,
	level integer NOT NULL DEFAULT 1,
	evasion integer NOT NULL,
	major_threshold integer NOT NULL,
	severe_threshold integer NOT NULL,
	hp_marked integer NOT NULL DEFAULT 0,
	hp_max integer NOT NULL,
	stress_marked integer NOT NULL DEFAULT 0,
	stress_max integer NOT NULL DEFAULT 6,
	hope integer NOT NULL DEFAULT 2,
	armor_marked integer NOT NULL DEFAULT 0,
	armor_max integer NOT NULL DEFAULT 0,
	vulnerable boolean NOT NULL DEFAULT false,
	restrained boolean NOT NULL DEFAULT false,
	hidden boolean NOT NULL DEFAULT false,
	notes text NOT NULL DEFAULT '',
	gold_handfuls integer NOT NULL DEFAULT 0,
	gold_bags integer NOT NULL DEFAULT 0,
	gold_chests integer NOT NULL DEFAULT 0,
	created_at timestamptz NOT NULL DEFAULT now(),
	seq bigserial
);
